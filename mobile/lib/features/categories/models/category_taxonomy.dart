  /// Find a category by ID or return fallback
  static MainCategoryItem getCategoryById(int id) {
    return allCategories.firstWhere(
      (cat) => cat.id == id,
      orElse: () => allCategories.first,
    );
  }

  /// Find a category by slug
  static MainCategoryItem? getCategoryBySlug(String slug) {
    try {
      return allCategories.firstWhere((cat) => cat.slug == slug);
    } catch (_) {
      return null;
    }
  }

  /// Get subcategories for a given category ID
  static List<SubcategoryItem> getSubcategoriesFor(int categoryId) {
    final cat = allCategories.firstWhere(
      (c) => c.id == categoryId,
      orElse: () => allCategories.first,
    );
    return cat.subcategories;
  }
