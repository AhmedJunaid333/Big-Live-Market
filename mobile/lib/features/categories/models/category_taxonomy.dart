import 'package:flutter/material.dart';

/// Represents a single subcategory item in the taxonomy with detailed tags
class SubcategoryItem {
  final int id;
  final String slug;
  final String name;
  final IconData icon;
  final String? subtitle;
  final int sampleCount;
  final List<String> tags;
  final String? imageAsset;

  const SubcategoryItem({
    required this.id,
    required this.slug,
    required this.name,
    required this.icon,
    this.subtitle,
    this.sampleCount = 0,
    this.tags = const [],
    this.imageAsset,
  });
}

/// Represents a main category with its child subcategories
class MainCategoryItem {
  final int id;
  final String slug;
  final String name;
  final IconData icon;
  final Color tint;
  final String imageAsset;
  final String subtitle;
  final List<SubcategoryItem> subcategories;

  const MainCategoryItem({
    required this.id,
    required this.slug,
    required this.name,
    required this.icon,
    required this.tint,
    required this.imageAsset,
    required this.subtitle,
    required this.subcategories,
  });
}

